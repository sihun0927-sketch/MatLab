% sol0601_1.m — 6.1 연습문제 1
% 화씨(°F)를 켈빈(K)으로 바꾸는 함수를 만들고 여러 온도에 적용한다.
% 별도 파일로 저장한다면 파일 이름은 f2k.m 이어야 한다.

clear; clc

F = [-40 32 98.6 212];
K = f2k(F);

for i = 1:numel(F)
    fprintf('%7.1f °F = %7.2f K\n', F(i), K(i));
end

function K = f2k(F)
% F2K  화씨를 켈빈으로 변환한다.
%   K = F2K(F) 는 (F-32)*5/9 + 273.15 를 반환한다.
%   F 는 스칼라, 벡터, 행렬 모두 가능하다.
K = (F - 32) * 5/9 + 273.15;
end
