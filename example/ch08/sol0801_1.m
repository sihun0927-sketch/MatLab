% sol0801_1.m — 8.1 연습문제 1: 관계·논리 연산 결과 예측

clear; clc

x = [3, -1, 0, 7, 2];
y = [1,  1, 0, 5, 9];

a = x >= y                  % 1 0 1 1 0
b = x ~= y & x > 0          % 1 0 0 1 1
c = xor(x > 0, y > 0)       % 0 1 0 0 0   ← 셋째는 둘 다 거짓이라 0
d = ~x                      % 0 0 1 0 0   ← 0 인 곳만 1
e = x & y                   % 1 1 0 1 1   ← 0 이 아니면 true 로 본다

class(d)                    % logical
