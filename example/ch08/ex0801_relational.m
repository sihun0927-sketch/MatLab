% ex0801_relational.m — 관계 연산자와 logical 배열 (8.1)

clear; clc

%% 스칼라끼리 비교: 결과는 true(1) 또는 false(0)
x = 5;
y = 1;
x < y                       % 0
class(x < y)                % 'logical' — double 이 아니다

%% 관계 연산자 6개 (x = 5, y = 1)
op  = ["<"; "<="; ">"; ">="; "=="; "~="];
res = [x < y; x <= y; x > y; x >= y; x == y; x ~= y];
disp(table(op, res))

%% 배열끼리 비교: 대응하는 원소끼리 → 같은 크기의 logical 배열
x = [1, 2, 3, 4, 5];
y = [-2, 0, 2, 4, 6];
x < y                       % 0 0 0 0 1

%% 배열과 스칼라 비교: 스칼라가 모든 원소와 비교된다
x > 2                       % 0 0 1 1 1

%% 0 이 아니면 true
logical([-3, 0, 0.1, 2])    % 1 0 1 1

%% 배열 전체가 참이려면 모든 원소가 1 이어야 한다
all(x < y)                  % 0 — 마지막 하나만 참
any(x < y)                  % 1 — 하나라도 참

%% == 와 = 는 다르다
x = 5;                      % 대입: x 라는 메모리에 5 를 넣는다
x == 3                      % 비교: 5 와 3 이 같은가? → 0
