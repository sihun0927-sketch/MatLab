% sol0801_2.m — 8.1 연습문제 2: 실수 비교는 == 대신 허용오차로

clear; clc

0.1 + 0.2 == 0.3            % 0 !
fprintf('0.1 + 0.2 = %.20f\n', 0.1 + 0.2);
fprintf('0.3       = %.20f\n', 0.3);

tol = 1e-12;
abs((0.1 + 0.2) - 0.3) < tol            % 1

% 배열도 똑같이
t = 0:0.1:1;
find(t == 0.3)              % 1x0 empty  ← 0.3 이 있는데도 못 찾는다
find(abs(t - 0.3) < tol)    % 4
