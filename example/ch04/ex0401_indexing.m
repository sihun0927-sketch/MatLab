% Ch4.1 - 인덱스 번호로 배열 원소 읽기/쓰기, 배열 확장

B = [1.5, 3.1];
S = [3.0, B]                % S = [3.0 1.5 3.1]

value = S(2)                 % 인덱스 번호로 값을 읽는다 (1부터 시작)

S(2) = -1                    % 인덱스로 값을 바꿀 수도 있다

S(4) = 5.5                   % 범위를 벗어난 인덱스에 값을 넣으면 배열이 늘어난다

S(8) = 9.5                   % 중간에 빈 자리가 생기면 0으로 채워진다 (S(5:7) == 0)
