% Ch4.3 - diag: 대각선 추출 vs 대각 행렬 생성

A = [1 2 3
     3 4 5
     1 2 3];

mainDiag = diag(A)            % 입력이 "행렬"이면 -> 주대각선을 열벡터로 추출
upperDiag = diag(A, 1)        % 두 번째 입력으로 주대각선 기준 위/아래 대각선 지정

v = [1, 2, 3];
diagMatrix = diag(v)          % 입력이 "벡터"이면 -> 그 값을 대각선에 놓은 정방행렬 생성
                               % (diag는 입력이 행렬이냐 벡터냐에 따라 반대로 동작한다)
