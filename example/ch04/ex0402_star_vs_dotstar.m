% Ch4.2 - 스칼라 곱, 행렬곱(*) vs 원소별 곱(.*)

k = 2;
v = [1 2 3];
scalarTimesArray = k * v          % 스칼라 * 배열 -> 모든 원소에 곱함 (모호함 없음)

Arow = [1 2 3];                   % 1x3
Bcol = [4; 5; 6];                 % 3x1
matrixProduct = Arow * Bcol       % '*'는 선형대수 행렬곱 규칙을 따른다
                                   % (m x n) * (n x p) 처럼 안쪽 차원이 같아야 함
                                   % 여기서는 (1x3)*(3x1) -> 1x1 스칼라

C = [1 2 3];
D = [10 20 30];
elementwise = C .* D              % '.*'는 같은 위치 원소끼리 곱한다 (원소별 곱)
                                   % C, D는 크기가 같아야 한다 (여기서는 1x3)
