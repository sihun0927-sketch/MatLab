% Ch4.1 - 배열 정의(defining)와 결합(concatenation)

A = [3.5]                  % 스칼라도 1x1 배열이다
B = [1.5, 3.1]              % 쉼표로 원소 구분
B2 = [1.5 3.1]              % 공백으로 구분해도 동일한 결과

C = [-1, 0, 0
      1, 1, 0
      1, -1, 0
      0, 0, 2]              % 세미콜론 대신 줄바꿈으로 새 행을 표시해도 된다

F = [1, 52, 64, 197, 42, -42, ...
     55, 82, 22, 109]       % 한 줄에 다 못 쓸 때는 콤마+말줄임표(...)로 이어쓴다

S = [3.0, B]                % 이미 정의된 배열 B를 이용해 새 배열 S를 정의
T = [1, 2, 3; S]            % 행렬끼리도 결합 가능 (T는 2x3)
