% sol0722_1.m — 7.2.2 연습문제 1
% 화씨 0~100 도를 10 도 간격으로 섭씨·켈빈으로 바꾼 표를 만든다.
% 핵심은 (1) 행으로 쌓아 열 우선 소비를 맞추고 (2) 폭으로 열을 정렬하는 것.

clear; clc

F = 0:10:100;
C = (F - 32) * 5/9;
K = C + 273.15;

% 머리글은 숫자 폭과 같은 폭으로 찍어야 열이 맞는다
fprintf('%8s %9s %9s\n', 'F', 'C', 'K');
fprintf('%s\n', repmat('-', 1, 28));

% [F; C; K] 로 쌓으면 열 우선 소비가 (F(1),C(1),K(1)), (F(2),...) 순서가 된다
fprintf('%8.1f %9.2f %9.2f\n', [F; C; K]);

fprintf('\n쌓은 배열의 크기 = %s (3 행 x %d 열)\n', mat2str(size([F; C; K])), numel(F));
fprintf('열 우선으로 읽히므로 한 줄에 F, C, K 가 차례로 들어간다.\n');

fprintf('\n--- 잘못 쌓으면 ([F'', C'', K''], 11x3) 처음 두 줄 ---\n');
wrong = [F', C', K'];
fprintf('%8.1f %9.2f %9.2f\n', wrong(1:2, :));
fprintf('(열 우선이라 F 끼리 먼저 소비되어 한 줄에 F 가 셋 들어간다)\n');
