% 같은 숫자들을 %f, %e, %g 로 나란히 찍어 차이를 눈으로 비교한다.

clear; clc

vals = [0.000123, 1.5, 12345.6789, 1234567890, pi];

fprintf('%14s %18s %18s %14s\n', '값', '%f', '%e', '%g');
fprintf('%s\n', repmat('-', 1, 68));
for v = vals
    fprintf('%14g %18f %18e %14g\n', v, v, v, v);
end

fprintf('\n읽는 법\n');
fprintf('  %%f : 언제나 고정소수점. 큰 수는 길어지고, 작은 수는 0 만 보인다.\n');
fprintf('  %%e : 언제나 지수 표기. 자릿수가 일정해 열 맞추기에 좋다.\n');
fprintf('  %%g : %%f 와 %%e 중 짧은 쪽. 유효숫자 6 개가 기본이다.\n');

fprintf('\n정밀도를 주면 뜻이 조금 달라진다\n');
x = 12345.6789;
fprintf('  %%.3f → %.3f   (소수점 아래 3 자리)\n', x);
fprintf('  %%.3e → %.3e   (가수의 소수점 아래 3 자리)\n', x);
fprintf('  %%.3g → %.3g   (유효숫자 전체가 3 개)\n', x);

fprintf('\n%%d 에 정수가 아닌 값을 주면 지수 표기로 넘어간다\n');
fprintf('  %%d 에 42   → %d\n', 42);
fprintf('  %%d 에 42.5 → %d   ← 반올림이 아니라 형식이 바뀐다\n', 42.5);
