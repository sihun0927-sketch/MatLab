%% 2.4 연습문제 1: 벡터/행렬에서 / 와 ./ 비교
v = [2 4 6 8];
disp(v/2)     % [1 2 3 4] - 벡터를 스칼라로 나눌 때는 / 와 ./ 결과가 같다
disp(v./2)    % 동일 결과

A = [1 2; 3 4];
disp(A/2)     % 스칼라로 나눌 때는 행렬에서도 / 와 ./ 결과가 같다
disp(A./2)

% 결론: 오른쪽 피연산자가 "스칼라"인 경우 /와 ./는 항상 같은 결과를 낸다.
% 스칼라 나눗셈에는 행렬 역행렬 규칙이 끼어들 여지가 없기 때문이다.
% 반면 오른쪽 피연산자가 배열/행렬이면 /는 역행렬 기반 연산으로 바뀌어 ./ 와 달라진다.
